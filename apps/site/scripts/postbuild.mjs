// Runs after `vite build` (the adapter has written .svelte-kit/cloudflare). It:
//  1. puts a small entry Worker in front of SvelteKit's, so pages with a Markdown twin answer
//     `Accept: text/markdown` at their own URL (src/lib/negotiate.js);
//  2. routes page requests through the Worker (assets.run_worker_first), except /_app/*;
//  3. for an indexable build (KOFRA_INDEXABLE=true), drops X-Robots-Tag from the built _headers.
import { copyFileSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const OUT = '.svelte-kit/cloudflare';
const WORKER = path.join(OUT, 'worker');
const CLIENT = path.join(OUT, 'client');

const walk = (dir) =>
	readdirSync(dir).flatMap((n) => {
		const f = path.join(dir, n);
		return statSync(f).isDirectory() ? walk(f) : [f];
	});

const twins = walk(CLIENT)
	.filter((f) => f.endsWith('.md'))
	.map((f) => '/' + path.relative(CLIENT, f).split(path.sep).join('/'))
	.sort();
if (twins.length === 0) throw new Error('postbuild: no Markdown twins in the build output');

copyFileSync('src/lib/negotiate.js', path.join(WORKER, 'negotiate.js'));
writeFileSync(
	path.join(WORKER, 'entry.js'),
	`// Generated by scripts/postbuild.mjs. Do not edit.\n` +
		`import app from './index.js';\n` +
		`import { withMarkdown } from './negotiate.js';\n` +
		`export default withMarkdown(app, new Set(${JSON.stringify(twins)}));\n`
);

const configFile = path.join(WORKER, 'wrangler.json');
const config = JSON.parse(readFileSync(configFile, 'utf8'));
if (config.main !== 'index.js' && config.main !== 'entry.js') {
	throw new Error(`postbuild: unexpected main ${config.main}; the adapter output changed`);
}
config.main = 'entry.js';
config.assets = { ...config.assets, run_worker_first: ['/*', '!/_app/*'] };
writeFileSync(configFile, JSON.stringify(config, null, 2));

if (process.env.KOFRA_INDEXABLE === 'true') {
	const headersFile = path.join(CLIENT, '_headers');
	const kept = readFileSync(headersFile, 'utf8')
		.split('\n')
		.filter((l) => !/^\s+X-Robots-Tag:/i.test(l));
	writeFileSync(headersFile, kept.join('\n'));
}

console.log(
	`postbuild: ${twins.length} Markdown twins; entry Worker installed; indexable=${process.env.KOFRA_INDEXABLE === 'true'}`
);
