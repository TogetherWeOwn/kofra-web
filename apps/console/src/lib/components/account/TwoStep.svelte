<script lang="ts">
	import { Button } from '@kofra/ui';
	import { goto } from '$app/navigation';
	import { resolve } from '$app/paths';
	import type { ShownProblem } from '#lib/types.js';
	import CopyField from '../CopyField.svelte';
	import ActionForm from './ActionForm.svelte';
	import Field from './Field.svelte';
	import RecoveryReveal from './RecoveryReveal.svelte';

	let {
		enabled,
		hasPasskeys,
		disable,
		csrf,
		result
	}: {
		enabled: boolean;
		hasPasskeys: boolean;
		disable: boolean;
		csrf?: string;
		result: {
			section: string;
			secret?: string;
			qr?: string;
			codes?: string[] | null;
			confirming?: boolean;
			field?: string;
			problem?: ShownProblem;
		} | null;
	} = $props();

	const accountUrl = resolve('/(app)/account');

	function discardSetup(event: MouseEvent) {
		if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
		event.preventDefault();
		void goto(resolve('/(app)/account#two-step'), { refreshAll: true });
	}
</script>

<section class="card pad" aria-labelledby="two-step">
	<h2 id="two-step">Two-step verification</h2>
	<p>Use an authenticator app to add a second step to sign-in.</p>
	<p>{enabled ? 'On' : 'Off'}</p>
	{#if result?.codes}<RecoveryReveal codes={result.codes} />{/if}
	{#if enabled}
		{#if disable || result?.section === 'totpDisable'}
			<p>
				Turn off the authenticator app? {#if !hasPasskeys}Your recovery codes will also stop
					working.{/if}
			</p>
			<ActionForm action="?/totpDisable" {csrf} {result}>
				<div class="actions">
					<Button type="submit">Turn off</Button>
					<a href="{accountUrl}?resetSetup=1#two-step" onclick={discardSetup}>Cancel</a>
				</div>
			</ActionForm>
		{:else}
			<div class="actions">
				<a class="btn-plain" href="{resolve('/(app)/account')}?disable=1#two-step">Turn off</a>
			</div>
		{/if}
	{:else if result?.secret || result?.confirming}
		{#if result.secret}
			<p>Scan the QR code or enter the setup key in your authenticator app.</p>
			{#if result.qr}
				<div class="setup-qr">
					<!-- eslint-disable-next-line svelte/no-at-html-tags -- generated by uqr on the server -->
					{@html result.qr}
				</div>
			{/if}
			<CopyField id="authenticator-secret" label="Setup key" value={result.secret} />
		{/if}
		<ActionForm action="?/totpConfirm" {csrf} {result}>
			<Field
				name="code"
				id="totp-code"
				label="Code"
				autocomplete="one-time-code"
				inputmode="numeric"
				{result}
			/>
			{#if !hasPasskeys}
				<!-- Its own ID: the password section on this page already has "password". -->
				<Field
					name="password"
					id="totp-password"
					label="Current password"
					type="password"
					autocomplete="current-password"
					{result}
				/>
			{/if}
			<div class="actions"><Button type="submit">Confirm setup</Button></div>
		</ActionForm>
		<p><a href="{accountUrl}?resetSetup=1#two-step" onclick={discardSetup}>Start over</a></p>
	{:else}
		<ActionForm action="?/totpBegin" {csrf} {result}>
			<div class="actions"><Button type="submit">Set up</Button></div>
		</ActionForm>
	{/if}
</section>

<style>
	.setup-qr {
		width: 12rem;
		max-width: 100%;
	}
</style>
